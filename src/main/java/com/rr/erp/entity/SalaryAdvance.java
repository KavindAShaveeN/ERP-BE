package com.rr.erp.entity;

import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.UUID;

/** An advance paid to an employee out of a cash (petty cash) account, recovered from later salary payments. */
@Getter
@Setter
public class SalaryAdvance {

    public static final String STATUS_OPEN = "OPEN";
    public static final String STATUS_PARTIAL = "PARTIAL";
    public static final String STATUS_CLOSED = "CLOSED";
    public static final String STATUS_VOID = "VOID";

    private UUID advanceId;

    // Generated by the server
    private String advanceCode;

    // The employee who receives the advance
    @NotBlank(message = "Employee code is required")
    private String employeeCode;

    // The cash account the advance is paid from
    @NotNull(message = "Cash account is required")
    private UUID cashAccountId;

    private UUID cashTransactionId;

    @NotNull(message = "Amount is required")
    @DecimalMin(value = "0.01", message = "Amount must be greater than zero")
    @Digits(integer = 13, fraction = 2, message = "Amount must have at most 13 digits and 2 decimal places")
    private BigDecimal amount;

    private BigDecimal recoveredAmount;

    // Defaults to today
    private LocalDate advanceDate;

    private String status;
    private String remarks;

    // Who recorded it
    @NotBlank(message = "Created by is required")
    private String createdBy;

    private LocalDateTime createdAt;

    // Read-only, joined / derived
    private BigDecimal outstandingAmount;
    private String employeeName;
    private String cashAccountName;
    private String cashTransactionCode;
}
