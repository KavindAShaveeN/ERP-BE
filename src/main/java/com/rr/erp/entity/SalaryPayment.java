package com.rr.erp.entity;

import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.UUID;

/** A salary paid to an employee out of a cash (petty cash) account, net of any advance recovered. */
@Getter
@Setter
public class SalaryPayment {

    public static final String STATUS_PAID = "PAID";
    public static final String STATUS_VOID = "VOID";

    private UUID salaryPaymentId;

    // Generated by the server
    private String paymentCode;

    @NotBlank(message = "Employee code is required")
    private String employeeCode;

    @NotBlank(message = "Salary period is required")
    @Pattern(regexp = "^[0-9]{4}-(0[1-9]|1[0-2])$", message = "Salary period must be in yyyy-MM format")
    private String salaryPeriod;

    @NotNull(message = "Gross amount is required")
    @DecimalMin(value = "0.01", message = "Gross amount must be greater than zero")
    @Digits(integer = 13, fraction = 2, message = "Gross amount must have at most 13 digits and 2 decimal places")
    private BigDecimal grossAmount;

    // Request: optional, null means recover all outstanding advance up to the gross. Response: the amount recovered.
    @DecimalMin(value = "0.00", message = "Advance deduction cannot be negative")
    @Digits(integer = 13, fraction = 2, message = "Advance deduction must have at most 13 digits and 2 decimal places")
    private BigDecimal advanceDeducted;

    private BigDecimal netAmount;

    // The cash account the net salary is paid from (not needed when the net is zero)
    private UUID cashAccountId;

    private UUID cashTransactionId;

    // Defaults to today
    private LocalDate paymentDate;

    private String status;
    private String remarks;

    @NotBlank(message = "Created by is required")
    private String createdBy;

    private LocalDateTime createdAt;

    // Read-only, joined
    private String employeeName;
    private String cashAccountName;
    private String cashTransactionCode;
}
