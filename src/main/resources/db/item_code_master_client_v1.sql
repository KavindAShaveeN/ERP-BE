INSERT INTO item_category (item_type_id, item_category_code, item_category_name, code_slug, name_slug)
SELECT DISTINCT t.item_type_id, c.cat_code, c.cat_name,
       lower(regexp_replace(c.cat_code, '[^A-Za-z0-9]', '', 'g')), lower(regexp_replace(c.cat_name, '[^A-Za-z0-9]', '', 'g'))
FROM client_codes c JOIN item_type t ON lower(t.item_type_name) = lower(c.type_name)
ON CONFLICT DO NOTHING;

INSERT INTO item_subcategory (item_category_id, item_subcategory_code, item_subcategory_name, code_slug, name_slug)
SELECT DISTINCT cat.item_category_id, c.sub_code, c.sub_name,
       lower(regexp_replace(c.sub_code, '[^A-Za-z0-9]', '', 'g')), lower(regexp_replace(c.sub_name, '[^A-Za-z0-9]', '', 'g'))
FROM client_codes c
JOIN item_type t ON lower(t.item_type_name) = lower(c.type_name)
JOIN item_category cat ON cat.item_type_id = t.item_type_id AND cat.item_category_code = c.cat_code
ON CONFLICT DO NOTHING;

INSERT INTO item_subsubcategory (item_subcategory_id, item_subsubcategory_code, item_subsubcategory_name, code_slug, name_slug)
SELECT DISTINCT sub.item_subcategory_id, c.ss_code, c.ss_name,
       lower(regexp_replace(c.ss_code, '[^A-Za-z0-9]', '', 'g')), lower(regexp_replace(c.ss_name, '[^A-Za-z0-9]', '', 'g'))
FROM client_codes c
JOIN item_type t ON lower(t.item_type_name) = lower(c.type_name)
JOIN item_category cat ON cat.item_type_id = t.item_type_id AND cat.item_category_code = c.cat_code
JOIN item_subcategory sub ON sub.item_category_id = cat.item_category_id AND sub.item_subcategory_code = c.sub_code
ON CONFLICT DO NOTHING;

