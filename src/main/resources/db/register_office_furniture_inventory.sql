JOIN item_category c ON c.item_type_id = 3 AND c.code_slug = 'of'
JOIN item_subcategory sc ON sc.item_category_id = c.item_category_id AND sc.item_subcategory_code = s.code
WHERE NOT EXISTS (SELECT 1 FROM item_subsubcategory x WHERE x.item_subcategory_id = sc.item_subcategory_id
                  AND x.code_slug = i.numtxt);

